/**
 * Pre-compile Vue templates into render functions.
 *
 * The WASM extension iframe has a strict CSP that blocks `unsafe-eval`,
 * which Vue's runtime template compiler needs. This script compiles the
 * templates at build time so the runtime compiler is not needed.
 *
 * Usage: node build-templates.js
 */
const fs = require('fs');
const path = require('path');
const { compile } = require('@vue/compiler-dom');

const ROOT = path.join(__dirname);

function compileTemplate(htmlFile, outputFile, varName) {
  const html = fs.readFileSync(htmlFile, 'utf8');

  // Extract the template from inside <div id="q-app" ...>...</div>
  const match = html.match(/<div id="q-app"[^>]*>([\s\S]*?)<\/div>\s*<script/i);
  if (!match) {
    throw new Error(`Could not find #q-app template in ${htmlFile}`);
  }
  const template = match[1].trim();

  // Compile the template
  const result = compile(template, {
    mode: 'function',
    prefixIdentifiers: true,
  });

  // The compiled code is a function body. Wrap it in an exported function.
  const code = `// Auto-generated by build-templates.js — DO NOT EDIT
// Pre-compiled Vue template for ${htmlFile}
window.${varName} = function() {
${result.code}
};
`;

  fs.writeFileSync(outputFile, code);
  console.log(`Compiled ${htmlFile} -> ${outputFile} (${code.length} bytes)`);
}

// Compile index template
compileTemplate(
  path.join(ROOT, 'templates', 'index.html'),
  path.join(ROOT, 'static', 'js', 'index-template.js'),
  'INDEX_RENDER_FN'
);

// Compile redeem template
compileTemplate(
  path.join(ROOT, 'templates', 'redeem.html'),
  path.join(ROOT, 'static', 'js', 'redeem-template.js'),
  'REDEEM_RENDER_FN'
);

// Compile claim template
compileTemplate(
  path.join(ROOT, 'templates', 'claim.html'),
  path.join(ROOT, 'static', 'js', 'claim-template.js'),
  'CLAIM_RENDER_FN'
);

console.log('All templates compiled successfully.');
